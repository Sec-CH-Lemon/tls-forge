#!/bin/sh
# Regenerate THIRD-PARTY-NOTICES.txt from the module cache.
#
# This is not paperwork. The npm packages ship a compiled Go binary, and a Go
# binary is statically linked: every dependency below travels inside it. All of
# them are BSD- or MIT-style, and all of those licences require the copyright
# notice to accompany binary redistribution. So the notices have to be generated
# from what is actually linked, and regenerated when that changes.
#
#   ./scripts/notices.sh > THIRD-PARTY-NOTICES.txt
set -eu

cd "$(dirname "$0")/.."
module=$(go list -m)

cat <<EOF
THIRD-PARTY SOFTWARE NOTICES
============================

tls-forge compiles to a single static binary, so the software listed here is
linked into every copy of it that is distributed — including the binaries inside
the npm packages. Each licence below requires its copyright notice to travel
with that binary, which is why this file must travel with it too.

Generated by scripts/notices.sh. Regenerate it whenever the dependency set
changes; \`go list\` below is the source of truth, not this paragraph.

EOF

# Every module actually linked into the binary, as opposed to everything in
# go.sum: the test-only and tool dependencies are not redistributed.
go list -deps -f '{{if .Module}}{{.Module.Path}}{{"\t"}}{{.Module.Version}}{{"\t"}}{{.Module.Dir}}{{end}}' ./... |
  grep -v "^$module" | sort -u | while IFS="$(printf '\t')" read -r path version dir; do
    [ -n "$dir" ] || continue
    printf '\n%s\n%s %s\n%s\n\n' \
      "--------------------------------------------------------------------------------" \
      "$path" "$version" \
      "--------------------------------------------------------------------------------"

    licence=
    for candidate in "$dir"/*; do
      base=${candidate##*/}
      case $base in
        [Ll][Ii][Cc][Ee][Nn][Ss][Ee]*|[Ll][Ii][Cc][Ee][Nn][Cc][Ee]*|[Cc][Oo][Pp][Yy][Ii][Nn][Gg]*)
          licence=$base
          break
          ;;
      esac
    done
    if [ -z "$licence" ]; then
      # A module linked in without a licence is a question for a person, not
      # a gap to fill with a guess.
      echo "notices: $path $version ships no licence file" >&2
      exit 1
    fi
    cat "$dir/$licence"
  done

# The header-map hash is adapted from BSD-licensed rapidhash, not a Go module.
printf '\n%s\n%s\n%s\n\n' \
  "--------------------------------------------------------------------------------" \
  "rapidhash header-name hashing (internal/chromehash)" \
  "--------------------------------------------------------------------------------"
cat internal/chromehash/LICENSE
