#!/bin/sh
# Regenerate THIRD-PARTY-NOTICES.txt from the module cache.
#
# This is not paperwork. The npm packages ship a compiled Go binary, and a Go
# binary is statically linked: every dependency below travels inside it. All of
# them are BSD- or MIT-style, and all of those licences require the copyright
# notice to accompany binary redistribution. So the notices have to be generated
# from what is actually linked, and regenerated when that changes.
#
#   ./scripts/notices.sh > THIRD-PARTY-NOTICES.txt
set -eu

cd "$(dirname "$0")/.."
module=$(GOWORK=off go list -m)
notice_work=$(mktemp -d)
trap 'rm -rf "$notice_work"' EXIT HUP INT TERM

# Reuse the release builder's target inventory. This includes dependencies that
# are compiled only on another supported OS (for example Darwin's purego).
node --input-type=module -e 'import { TARGETS } from "./scripts/release-build.mjs"; for (const [os, arch] of TARGETS) console.log(os + " " + arch);' > "$notice_work/targets"
while read -r notice_os notice_arch; do
  CGO_ENABLED=0 GOOS="$notice_os" GOARCH="$notice_arch" GOWORK=off go list -deps \
    -f '{{if .Module}}{{.Module.Path}}{{"\t"}}{{.Module.Version}}{{"\t"}}{{.Module.Dir}}{{end}}' ./cmd/tls-forge
done < "$notice_work/targets" > "$notice_work/modules"

cat <<EOF
THIRD-PARTY SOFTWARE NOTICES
============================

tls-forge compiles to a single static binary, so the software listed here is
linked into at least one supported release binary, including the binaries inside
the npm packages. The same complete inventory travels with every distribution;
each applicable licence requires its copyright notice to accompany its binary.

Generated by scripts/notices.sh. Regenerate it whenever the dependency set
changes; \`go list\` below is the source of truth, not this paragraph.

EOF

# Union the modules actually linked for the shared release target inventory;
# test/tool-only requirements are not redistributed.
grep -v "^$module" "$notice_work/modules" | sort -u | while IFS="$(printf '\t')" read -r path version dir; do
    [ -n "$dir" ] || continue
    printf '\n%s\n%s %s\n%s\n\n' \
      "--------------------------------------------------------------------------------" \
      "$path" "$version" \
      "--------------------------------------------------------------------------------"

    licence=
    for candidate in "$dir"/*; do
      base=${candidate##*/}
      case $base in
        [Ll][Ii][Cc][Ee][Nn][Ss][Ee]*|[Ll][Ii][Cc][Ee][Nn][Cc][Ee]*|[Cc][Oo][Pp][Yy][Ii][Nn][Gg]*)
          licence=$base
          break
          ;;
      esac
    done
    if [ -z "$licence" ]; then
      # A module linked in without a licence is a question for a person, not
      # a gap to fill with a guess.
      echo "notices: $path $version ships no licence file" >&2
      exit 1
    fi
    cat "$dir/$licence"
  done

# The header-map hash is adapted from BSD-licensed rapidhash, not a Go module.
printf '\n%s\n%s\n%s\n\n' \
  "--------------------------------------------------------------------------------" \
  "rapidhash header-name hashing (internal/chromehash)" \
  "--------------------------------------------------------------------------------"
cat internal/chromehash/LICENSE

# The host hash primitive is ported from libc++, outside the Go module cache.
printf '\n%s\n%s\n%s\n\n' \
  "--------------------------------------------------------------------------------" \
  "LLVM libc++ host hashing (networkquality)" \
  "--------------------------------------------------------------------------------"
cat networkquality/LICENSE.libcxx.txt
